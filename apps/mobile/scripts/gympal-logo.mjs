/**
 * GymPal's face, in three layers, so it can blink and grin
 * (src/components/GymPal.tsx).
 *
 * Reads the logo, assets/gympal/gympal.svg (drawn for GymGO on 28 October
 * 2026: a kettlebell in a sweatband on GymGO's blue-violet), and writes:
 *  - src/lib/gymPalArt.ts: its three groups (body, eyes, mouth) as
 *    standalone SVGs, the body with the gradients it uses, to lay one over
 *    another in the app;
 *  - assets/gympal/gympal.png: the whole logo at 512 pixels, for anywhere
 *    an SVG won't do (an app store listing, a social post).
 *
 *   node scripts/gympal-logo.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const source = join(app, 'assets', 'gympal', 'gympal.svg');
const svg = readFileSync(source, 'utf8');

const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
const defs = svg.match(/<defs>[\s\S]*?<\/defs>/)?.[0];
const group = (id) => svg.match(new RegExp(`<g id="${id}">([\\s\\S]*?)\\n  </g>`))?.[1];
const layers = { body: group('body'), eyes: group('eyes'), mouth: group('mouth') };
if (!viewBox || !defs || Object.values(layers).some((layer) => !layer)) {
  console.error('gympal.svg needs a viewBox, <defs>, and groups with the ids body, eyes and mouth.');
  process.exit(1);
}

/** One layer as an SVG of its own: one line, extra spaces gone. */
const standalone = (inner, withDefs) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${withDefs ? defs : ''}${inner}</svg>`.replace(/\s*\n\s*/g, ' ').replace(/>\s+</g, '><');

writeFileSync(
  join(app, 'src', 'lib', 'gymPalArt.ts'),
  [
    '// Generated by scripts/gympal-logo.mjs from assets/gympal/gympal.svg. Do not edit by hand.',
    "// GymPal's face in three layers, laid one over another (components/GymPal.tsx).",
    '',
    `export const GYMPAL_BODY = ${JSON.stringify(standalone(layers.body, true))};`,
    `export const GYMPAL_EYES = ${JSON.stringify(standalone(layers.eyes, false))};`,
    `export const GYMPAL_MOUTH = ${JSON.stringify(standalone(layers.mouth, false))};`,
    '',
  ].join('\n'),
);

await sharp(Buffer.from(svg), { density: 600 }).resize(512, 512).png().toFile(join(app, 'assets', 'gympal', 'gympal.png'));
console.log('Wrote src/lib/gymPalArt.ts and assets/gympal/gympal.png.');
