/**
 * Emoji and flags for GymGO from Google's Noto 3D set
 * (https://github.com/googlefonts/noto-emoji, folder 3D/png), so they look
 * the same on every phone, computer and the website instead of each
 * system's own (Windows draws no flags at all).
 *
 * Takes Noto's 128-pixel pictures of the emoji GymGO shows (EMOJI below;
 * src/lib/emoji.test.ts checks the app asks for no others) and of every
 * country's flag in src/lib/countries.ts, saves them as WebP (emoji at
 * 128 pixels, flags at 96, about 3 KB each) in assets/emoji and
 * assets/flags, and copies the set's licence, the SIL Open Font License
 * 1.1, to assets/emoji/LICENSE.txt. The images, which only the bundler can
 * load, are listed in src/lib/emojiImages.ts.
 *
 *   git clone --depth 1 --filter=blob:none --sparse https://github.com/googlefonts/noto-emoji
 *   node scripts/noto-emoji.mjs path/to/noto-emoji
 *
 * With a sparse clone, the script names the files to check out first.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const noto = process.argv[2];
if (!noto || !existsSync(join(noto, 'LICENSE'))) {
  console.error('Usage: node scripts/noto-emoji.mjs path/to/noto-emoji');
  process.exit(1);
}

/** The emoji GymGO shows: celebrations and their samples, and the sound packs' samples. */
const EMOJI = ['💪', '🔥', '🏆', '⭐', '🎉', '🎊', '🎆', '🎵', '🕹️'];
const SIZE = 128;
const FLAG_SIZE = 96;

/** A Noto picture as a small WebP, at the given size. */
const save = (from, to, size, quality) => sharp(from).resize(size, size).webp({ quality, alphaQuality: 90, effort: 6 }).toFile(to);

/** As emojiKey in src/lib/emoji.ts: code points in hex, at least four digits, without U+FE0F. */
const keyOf = (text) =>
  [...text]
    .map((char) => char.codePointAt(0))
    .filter((point) => point !== 0xfe0f)
    .map((point) => point.toString(16).padStart(4, '0'))
    .join('_');
const flagKey = (code) => keyOf(String.fromCodePoint(...[...code].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65)));
const source = (key) => join(noto, '3D', 'png', String(SIZE), `emoji_u${key}.png`);

const countries = [...readFileSync(join(app, 'src', 'lib', 'countries.ts'), 'utf8').matchAll(/"code":"([A-Z]{2})"/g)].map((match) => match[1]);
const wanted = [...EMOJI.map((emoji) => source(keyOf(emoji))), ...countries.map((code) => source(flagKey(code)))];
const absent = wanted.filter((path) => !existsSync(path));
if (absent.length === wanted.length) {
  console.error(`None of the files are here. In a sparse clone, check them out first:\n  git -C ${noto} sparse-checkout add ${[...new Set(absent.map((path) => `/${path.slice(noto.length + 1)}`))].slice(0, 3).join(' ')} …`);
  process.exit(1);
}

for (const folder of ['emoji', 'flags']) {
  rmSync(join(app, 'assets', folder), { recursive: true, force: true });
  mkdirSync(join(app, 'assets', folder), { recursive: true });
}

const emojiLines = [];
for (const emoji of EMOJI) {
  const key = keyOf(emoji);
  if (!existsSync(source(key))) {
    console.error(`No Noto 3D picture for ${emoji} (${key}).`);
    process.exit(1);
  }
  await save(source(key), join(app, 'assets', 'emoji', `${key}.webp`), SIZE, 90);
  emojiLines.push(`  "${key}": require('../../assets/emoji/${key}.webp'), // ${emoji}`);
}

const flagLines = [];
const flagless = [];
for (const code of countries) {
  const from = source(flagKey(code));
  if (!existsSync(from)) {
    flagless.push(code);
    continue;
  }
  await save(from, join(app, 'assets', 'flags', `${code.toLowerCase()}.webp`), FLAG_SIZE, 85);
  flagLines.push(`  ${code}: require('../../assets/flags/${code.toLowerCase()}.webp'),`);
}

writeFileSync(
  join(app, 'assets', 'emoji', 'LICENSE.txt'),
  [
    'The emoji in assets/emoji and the flags in assets/flags are from Noto Emoji',
    '(3D/png), https://github.com/googlefonts/noto-emoji, by Google LLC, under the',
    "licence below (the repository's own LICENSE file).",
    '',
    readFileSync(join(noto, 'LICENSE'), 'utf8'),
  ].join('\n'),
);

writeFileSync(
  join(app, 'src', 'lib', 'emojiImages.ts'),
  [
    '// Generated by scripts/noto-emoji.mjs. Do not edit by hand.',
    "// Google's Noto 3D emoji and flags (SIL Open Font License 1.1: assets/emoji/LICENSE.txt),",
    '// which only the bundler can load. Emoji are keyed by emojiKey in emoji.ts, flags by country code.',
    '',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    'export const EMOJI_IMAGES: Record<string, ImageSourcePropType> = {',
    ...emojiLines,
    '};',
    '',
    '// prettier-ignore',
    'export const FLAG_IMAGES: Record<string, ImageSourcePropType> = {',
    ...flagLines,
    '};',
    '',
  ].join('\n'),
);

console.log(`${EMOJI.length} emoji and ${flagLines.length} flags copied${flagless.length ? `; no flag in Noto 3D for ${flagless.join(', ')}` : ''}.`);
