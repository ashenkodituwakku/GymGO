/**
 * Country flags for GymGO from Google's Noto 3D emoji set
 * (https://github.com/googlefonts/noto-emoji, folder 3D/png), so a flag looks
 * the same on every phone, computer and the website instead of each
 * system's own (Windows draws no flag emoji at all, only two letters).
 *
 * Takes Noto's 128-pixel picture of every country's flag in
 * src/lib/countries.ts, saves each as a 96-pixel WebP (about 4 KB) in
 * assets/flags, and copies the set's licence, the SIL Open Font License 1.1,
 * to assets/flags/LICENSE.txt. The images, which only the bundler can load,
 * are listed in src/lib/flagImages.ts.
 *
 *   git clone --depth 1 --filter=blob:none --sparse https://github.com/googlefonts/noto-emoji
 *   node scripts/noto-flags.mjs path/to/noto-emoji
 *
 * With a sparse clone, the script names the files to check out first.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const noto = process.argv[2];
if (!noto || !existsSync(join(noto, 'LICENSE'))) {
  console.error('Usage: node scripts/noto-flags.mjs path/to/noto-emoji');
  process.exit(1);
}

const SOURCE_SIZE = 128;
const SIZE = 96;

/** Noto's file name for a country's flag: its two regional indicator letters, in hex. */
const fileOf = (code) => `emoji_u${[...code].map((letter) => (0x1f1e6 + letter.charCodeAt(0) - 65).toString(16)).join('_')}.png`;
const source = (code) => join(noto, '3D', 'png', String(SOURCE_SIZE), fileOf(code));

const countries = [...readFileSync(join(app, 'src', 'lib', 'countries.ts'), 'utf8').matchAll(/"code":"([A-Z]{2})"/g)].map((match) => match[1]);
const absent = countries.filter((code) => !existsSync(source(code)));
if (absent.length === countries.length) {
  console.error(`None of the files are here. In a sparse clone, check them out first:\n  git -C ${noto} sparse-checkout add /3D/png/${SOURCE_SIZE}`);
  process.exit(1);
}

const folder = join(app, 'assets', 'flags');
rmSync(folder, { recursive: true, force: true });
mkdirSync(folder, { recursive: true });

const lines = [];
for (const code of countries) {
  if (!existsSync(source(code))) continue;
  await sharp(source(code)).resize(SIZE, SIZE).webp({ quality: 85, alphaQuality: 90, effort: 6 }).toFile(join(folder, `${code.toLowerCase()}.webp`));
  lines.push(`  ${code}: require('../../assets/flags/${code.toLowerCase()}.webp'),`);
}

writeFileSync(
  join(folder, 'LICENSE.txt'),
  [
    'The flags in this folder are from Noto Emoji (3D/png),',
    'https://github.com/googlefonts/noto-emoji, by Google LLC, under the licence',
    "below (the repository's own LICENSE file).",
    '',
    readFileSync(join(noto, 'LICENSE'), 'utf8'),
  ].join('\n'),
);

writeFileSync(
  join(app, 'src', 'lib', 'flagImages.ts'),
  [
    '// Generated by scripts/noto-flags.mjs. Do not edit by hand.',
    "// Google's Noto 3D flags (SIL Open Font License 1.1: assets/flags/LICENSE.txt), by country code,",
    '// which only the bundler can load.',
    '',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    '// prettier-ignore',
    'export const FLAG_IMAGES: Record<string, ImageSourcePropType> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);

console.log(`${lines.length} flags copied${absent.length ? `; no flag in Noto 3D for ${absent.join(', ')}` : ''}.`);
