/**
 * The weather symbols for GymGO (components/Weather.tsx): MET Norway's own
 * set for its forecast (https://github.com/metno/weathericons, from Yr's,
 * MIT licence: assets/weather/LICENSE.txt), one for each symbol code the
 * forecast uses ("partlycloudy_day", "rain", "heavysnowshowers_night"…).
 *
 * Their SVGs (in assets/weather/svg) are layered, with shading baked in as
 * pictures, more than the app's SVG drawing can show the same everywhere;
 * so each is made into a 144-pixel WebP once (about 2 KB, sharp enough at
 * 48 points on a 3× screen), and listed in src/lib/weatherArt.ts, which
 * only the bundler can load.
 *
 *   node scripts/weather-icons.mjs
 *
 * To update them: copy the repository's weather/svg folder over
 * assets/weather/svg, then run this.
 */

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const source = join(app, 'assets', 'weather', 'svg');
const out = join(app, 'assets', 'weather', 'icons');
const SIZE = 144;

const names = readdirSync(source)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort();
if (names.length === 0) {
  console.error('No SVGs in assets/weather/svg.');
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
let bytes = 0;
for (const name of names) {
  const image = await sharp(readFileSync(join(source, `${name}.svg`)), { density: 300 })
    .resize(SIZE, SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 90, alphaQuality: 100, effort: 6 })
    .toBuffer();
  writeFileSync(join(out, `${name}.webp`), image);
  bytes += image.length;
}

writeFileSync(
  join(app, 'src', 'lib', 'weatherArt.ts'),
  [
    '// Generated by scripts/weather-icons.mjs. Do not edit by hand.',
    "// MET Norway's weather symbols (from Yr's, MIT: assets/weather/LICENSE.txt), by the forecast's symbol code,",
    '// which only the bundler can load.',
    '',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    '// prettier-ignore',
    'export const WEATHER_ART: Record<string, ImageSourcePropType> = {',
    ...names.map((name) => `  ${name}: require('../../assets/weather/icons/${name}.webp'),`),
    '};',
    '',
  ].join('\n'),
);
console.log(`Wrote ${names.length} icons (${Math.round(bytes / 1024)} KB) to assets/weather/icons and src/lib/weatherArt.ts.`);
